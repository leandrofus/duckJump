// Command openapi-gen builds openapi/openapi.yaml from:
//   - openapi/root.yaml: the static part (info, security, shared components);
//   - the router in internal/server (Server.Handler): method, path, which
//     handler, and its access rule (public, authed(roles, …), pending(…));
//   - `openapi:operation` comment blocks above each handler, and
//     `openapi:schema Name` blocks anywhere in internal/**.
//
// The YAML blocks are separated from the declaration below them by a blank
// line: a comment attached to a declaration is a doc comment, and gofmt
// rewrites indented lines in doc comments, which breaks the YAML.
//
// Derived, so not repeated in comments: path parameters, security and roles,
// the CSRF header on state-changing requests, and the standard error
// responses (400 with a body, 401/403 when authenticated, 404 with a path
// parameter).
//
// It fails, writing nothing, when a route lacks its operation block, a $ref
// points nowhere, or a schema block placed above a struct does not list
// exactly the struct's JSON fields.
//
// Usage: go run ./cmd/openapi-gen [-check]
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

var check = flag.Bool("check", false, "fail if openapi/openapi.yaml is out of date instead of writing it")

func main() {
	flag.Parse()
	root, err := moduleRoot()
	if err == nil {
		err = run(root, *check)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "openapi-gen:", err)
		os.Exit(1)
	}
}

func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("go.mod not found")
		}
		dir = parent
	}
}

const apiPrefix = "/api/v1"

func run(root string, checkOnly bool) error {
	spec, err := loadRoot(filepath.Join(root, "openapi", "root.yaml"))
	if err != nil {
		return err
	}
	src, err := parseTree(filepath.Join(root, "internal"))
	if err != nil {
		return err
	}
	var errs []string

	routes, rerrs := src.routes()
	errs = append(errs, rerrs...)
	schemas, serrs := src.schemas()
	errs = append(errs, serrs...)

	components := spec["components"].(map[string]any)
	compSchemas := components["schemas"].(map[string]any)
	for name, s := range schemas {
		if _, dup := compSchemas[name]; dup {
			errs = append(errs, fmt.Sprintf("schema %s defined twice", name))
		}
		compSchemas[name] = s
	}

	paths := map[string]any{}
	for _, r := range routes {
		if !strings.HasPrefix(r.path, apiPrefix+"/") {
			continue
		}
		path := strings.TrimPrefix(r.path, apiPrefix)
		block, ok := src.operationBlock(r.handler)
		if !ok {
			errs = append(errs, fmt.Sprintf("%s %s: handler %s has no openapi:operation block", r.method, r.path, r.handler))
			continue
		}
		op, err := buildOperation(r, path, block)
		if err != nil {
			errs = append(errs, fmt.Sprintf("%s %s (%s): %v", r.method, r.path, r.handler, err))
			continue
		}
		item, _ := paths[path].(map[string]any)
		if item == nil {
			item = map[string]any{}
			paths[path] = item
		}
		m := strings.ToLower(r.method)
		if _, dup := item[m]; dup {
			errs = append(errs, fmt.Sprintf("route %s %s registered twice", r.method, r.path))
		}
		item[m] = op
	}
	spec["paths"] = paths

	errs = append(errs, checkRefs(spec)...)
	if len(errs) > 0 {
		sort.Strings(errs)
		return fmt.Errorf("%d problem(s):\n  %s", len(errs), strings.Join(errs, "\n  "))
	}

	var buf bytes.Buffer
	buf.WriteString("# Generated by cmd/openapi-gen from openapi/root.yaml and comments in internal/**. DO NOT EDIT.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(spec); err != nil {
		return err
	}
	out := filepath.Join(root, "openapi", "openapi.yaml")
	if checkOnly {
		cur, _ := os.ReadFile(out)
		if !bytes.Equal(cur, buf.Bytes()) {
			return fmt.Errorf("openapi/openapi.yaml is out of date: run `make openapi`")
		}
		return nil
	}
	return os.WriteFile(out, buf.Bytes(), 0o644)
}

func loadRoot(path string) (map[string]any, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var spec map[string]any
	if err := yaml.Unmarshal(b, &spec); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if err := suspiciousKeys(spec); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	comps, _ := spec["components"].(map[string]any)
	if comps == nil {
		comps = map[string]any{}
		spec["components"] = comps
	}
	if _, ok := comps["schemas"].(map[string]any); !ok {
		comps["schemas"] = map[string]any{}
	}
	return spec, nil
}

var pathParam = regexp.MustCompile(`\{([a-zA-Z_][a-zA-Z0-9_]*)\}`)

var statusText = map[string]string{
	"400": "Invalid request", "401": "Not authenticated", "403": "Not allowed (role, grant or missing CSRF header)",
	"404": "Not found", "409": "Conflicts with the current state", "429": "Too many attempts",
	"501": "Not implemented yet", "500": "Internal error",
}

func schemaRef(v any) (any, error) {
	s, ok := v.(string)
	if !ok {
		return v, nil // an inline schema
	}
	if name, isArr := strings.CutPrefix(s, "[]"); isArr {
		return map[string]any{"type": "array", "items": map[string]any{"$ref": "#/components/schemas/" + name}}, nil
	}
	return map[string]any{"$ref": "#/components/schemas/" + s}, nil
}

func buildOperation(r route, path string, block string) (map[string]any, error) {
	var op map[string]any
	if err := yaml.Unmarshal([]byte(block), &op); err != nil {
		return nil, fmt.Errorf("operation YAML: %w", err)
	}
	if err := suspiciousKeys(op); err != nil {
		return nil, err
	}
	if op == nil {
		op = map[string]any{}
	}
	if _, ok := op["summary"]; !ok {
		return nil, fmt.Errorf("missing summary")
	}
	op["operationId"] = r.handler
	if _, ok := op["tags"]; !ok {
		seg := strings.SplitN(strings.TrimPrefix(path, "/"), "/", 2)[0]
		op["tags"] = []any{seg}
	}

	// Parameters: declared ones first, then path params and CSRF.
	params, _ := op["parameters"].([]any)
	declared := map[string]bool{}
	for _, p := range params {
		if pm, ok := p.(map[string]any); ok {
			declared[fmt.Sprint(pm["in"])+":"+fmt.Sprint(pm["name"])] = true
		}
	}
	names := pathParam.FindAllStringSubmatch(path, -1)
	for _, m := range names {
		if !declared["path:"+m[1]] {
			params = append(params, map[string]any{"name": m[1], "in": "path", "required": true, "schema": map[string]any{"type": "string"}})
		}
	}
	mutating := r.method != "GET" && r.method != "HEAD"
	if mutating {
		params = append(params, map[string]any{"$ref": "#/components/parameters/CSRF"})
	}
	if len(params) > 0 {
		op["parameters"] = params
	}

	if rb, ok := op["requestBody"].(map[string]any); ok {
		sch, has := rb["schema"]
		if !has {
			return nil, fmt.Errorf("requestBody needs schema")
		}
		ref, err := schemaRef(sch)
		if err != nil {
			return nil, err
		}
		req := true
		if v, ok := rb["required"].(bool); ok {
			req = v
		}
		body := map[string]any{"required": req, "content": map[string]any{"application/json": map[string]any{"schema": ref}}}
		if d, ok := rb["description"]; ok {
			body["description"] = d
		}
		op["requestBody"] = body
	}

	resps, _ := op["responses"].(map[string]any)
	if len(resps) == 0 {
		return nil, fmt.Errorf("missing responses")
	}
	auto := func(code string, when bool) {
		if _, ok := resps[code]; !ok && when {
			resps[code] = "Error"
		}
	}
	auto("400", op["requestBody"] != nil || mutating && r.access != accessPublic)
	auto("401", r.access != accessPublic)
	auto("403", r.access == accessRoles && len(r.roles) < r.allRoles || mutating)
	auto("404", len(names) > 0)
	for code, v := range resps {
		switch x := v.(type) {
		case string:
			if x != "Error" {
				return nil, fmt.Errorf("response %s: shorthand must be Error", code)
			}
			resps[code] = errorResponse(code)
		case map[string]any:
			if sch, ok := x["schema"]; ok {
				ref, err := schemaRef(sch)
				if err != nil {
					return nil, err
				}
				delete(x, "schema")
				x["content"] = map[string]any{"application/json": map[string]any{"schema": ref}}
			}
			if _, ok := x["description"]; !ok {
				return nil, fmt.Errorf("response %s: missing description", code)
			}
			// 200/201 always carry a body here; no content means a typo
			// (e.g. schema swallowed into a quoted description).
			if _, has := x["content"]; !has && (code == "200" || code == "201") {
				return nil, fmt.Errorf("response %s: no schema or content", code)
			}
		default:
			return nil, fmt.Errorf("response %s: unexpected %T", code, v)
		}
	}
	op["responses"] = resps

	switch r.access {
	case accessPublic:
		op["security"] = []any{}
	case accessRoles:
		roles := make([]any, len(r.roles))
		for i, x := range r.roles {
			roles[i] = x
		}
		op["x-palta-roles"] = roles
		note := "Roles: " + strings.Join(r.roles, ", ") + "."
		if d, ok := op["description"].(string); ok && d != "" {
			op["description"] = strings.TrimRight(d, "\n") + "\n\n" + note
		} else {
			op["description"] = note
		}
	case accessPending:
		op["x-palta-mfa-pending-allowed"] = true
	}
	return op, nil
}

// suspiciousKeys catches the classic flow-mapping mistake: in
// `{ description: a, b }` the unquoted comma makes "b" a key. No key in
// these blocks legitimately contains a space or ends with a period.
func suspiciousKeys(v any) error {
	switch x := v.(type) {
	case map[string]any:
		for k, c := range x {
			if strings.Contains(k, " ") || strings.HasSuffix(k, ".") {
				return fmt.Errorf("suspicious key %q: quote values that contain commas", k)
			}
			if err := suspiciousKeys(c); err != nil {
				return err
			}
		}
	case []any:
		for _, c := range x {
			if err := suspiciousKeys(c); err != nil {
				return err
			}
		}
	}
	return nil
}

func errorResponse(code string) map[string]any {
	d := statusText[code]
	if d == "" {
		d = "Error " + code
	}
	return map[string]any{"description": d, "content": map[string]any{
		"application/json": map[string]any{"schema": map[string]any{"$ref": "#/components/schemas/Error"}}}}
}

// checkRefs reports every $ref that does not resolve inside the spec.
func checkRefs(spec map[string]any) []string {
	var errs []string
	var walk func(where string, v any)
	walk = func(where string, v any) {
		switch x := v.(type) {
		case map[string]any:
			if ref, ok := x["$ref"].(string); ok {
				if !resolves(spec, ref) {
					errs = append(errs, fmt.Sprintf("%s: unresolved $ref %s", where, ref))
				}
			}
			for k, c := range x {
				walk(where+"/"+k, c)
			}
		case []any:
			for i, c := range x {
				walk(where+"/"+strconv.Itoa(i), c)
			}
		}
	}
	walk("#", spec)
	return errs
}

func resolves(spec map[string]any, ref string) bool {
	parts, ok := strings.CutPrefix(ref, "#/")
	if !ok {
		return false
	}
	var cur any = spec
	for _, p := range strings.Split(parts, "/") {
		m, ok := cur.(map[string]any)
		if !ok {
			return false
		}
		if cur, ok = m[p]; !ok {
			return false
		}
	}
	return true
}
